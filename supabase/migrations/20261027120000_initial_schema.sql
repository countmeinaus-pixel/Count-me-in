create extension if not exists pgcrypto;

create table if not exists public.sports (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  first_name text not null,
  age integer not null check (age between 18 and 99),
  suburb text not null,
  bio text default '',
  photo_url text,
  phone_verified boolean not null default false,
  selfie_verified boolean not null default false,
  onboarding_complete boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profile_sports (
  profile_id uuid not null references public.profiles(id) on delete cascade,
  sport_id bigint not null references public.sports(id) on delete cascade,
  skill text not null check (skill in ('Beginner', 'Intermediate', 'Experienced')),
  created_at timestamptz not null default now(),
  primary key (profile_id, sport_id)
);

create table if not exists public.profile_availability (
  profile_id uuid not null references public.profiles(id) on delete cascade,
  availability text not null check (
    availability in ('Weekday mornings', 'Weekday evenings', 'Saturdays', 'Sundays', 'Flexible')
  ),
  created_at timestamptz not null default now(),
  primary key (profile_id, availability)
);

create index if not exists idx_profiles_suburb on public.profiles(suburb);
create index if not exists idx_profile_sports_sport on public.profile_sports(sport_id);

alter table public.profiles enable row level security;
alter table public.profile_sports enable row level security;
alter table public.profile_availability enable row level security;
alter table public.sports enable row level security;

drop policy if exists "Profiles are viewable by everyone" on public.profiles;
drop policy if exists "Users can insert their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Users can delete their own profile" on public.profiles;
drop policy if exists "Profile sport rows are viewable by everyone" on public.profile_sports;
drop policy if exists "Users can manage their own sport rows" on public.profile_sports;
drop policy if exists "Profile availability rows are viewable by everyone" on public.profile_availability;
drop policy if exists "Users can manage their own availability rows" on public.profile_availability;
drop policy if exists "Sports are viewable by everyone" on public.sports;
drop policy if exists "Sports are insertable by authenticated users" on public.sports;

create policy "Profiles are viewable by everyone"
on public.profiles for select using (true);

create policy "Users can insert their own profile"
on public.profiles for insert with check (auth.uid() = id);

create policy "Users can update their own profile"
on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

create policy "Users can delete their own profile"
on public.profiles for delete using (auth.uid() = id);

create policy "Profile sport rows are viewable by everyone"
on public.profile_sports for select using (true);

create policy "Users can manage their own sport rows"
on public.profile_sports for all using (auth.uid() = profile_id) with check (auth.uid() = profile_id);

create policy "Profile availability rows are viewable by everyone"
on public.profile_availability for select using (true);

create policy "Users can manage their own availability rows"
on public.profile_availability for all using (auth.uid() = profile_id) with check (auth.uid() = profile_id);

create policy "Sports are viewable by everyone"
on public.sports for select using (true);

create policy "Sports are insertable by authenticated users"
on public.sports for insert with check (auth.role() = 'authenticated');

